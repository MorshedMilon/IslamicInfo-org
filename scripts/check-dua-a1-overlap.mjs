/* check-dua-a1-overlap.mjs — READ ONLY. DUA-PAGE-CONTENT-SPEC.md §6 validation.
 *
 * Runs the spec's programmatic wave checks over every authored entry in
 * src/data/dua/page-copy.json — library-wide, not per batch, per §6.4.
 *
 *   §6.2  A1 word count within 80-150   (A1 = meaning + timing + reflection)
 *   §6.3  banned-phrase scan (§4 lists)
 *   §6.4  cross-page 12-gram overlap on A1 text only; any 12-word sequence on
 *         3+ pages is a templating leak. A2 (the Source & authenticity block)
 *         is excluded per the spec — it is generated, not authored, and
 *         legitimately repeats formulae.
 *   §6.5  specificity — each A1 carries a digit, proper noun or time expression
 *
 * Two generated blocks are scanned with the same 12-gram window, reported
 * separately because they are generated rather than authored: the page-intro
 * (.lede) and the Block B4 FAQ. The FAQ window carries two carve-outs, both
 * narrower than they look — see the notes at each: the <h3> question text, and
 * spans matching the record's own translation / transliteration / A1 VERBATIM
 * (owner-approved 2026-08-02). Generated connective phrasing is never exempt.
 *
 *   node scripts/check-dua-a1-overlap.mjs
 */
import fs from "node:fs";

const pc = JSON.parse(fs.readFileSync("src/data/dua/page-copy.json", "utf8"));
const entries = Object.entries(pc).filter(([k]) => k !== "_meta");

/* Corpus, keyed by id, and the reverse slug->id map. Needed only by the B4
   quoted-span carve-out below. */
const corpusById = new Map();
try {
  const c = JSON.parse(fs.readFileSync("src/data/dua/search-corpus.json", "utf8"));
  for (const d of c.duas) corpusById.set(d.id, d);
} catch { /* carve-out degrades to "exclude nothing", which can only over-report */ }
const idBySlug = new Map();
try {
  const lk = JSON.parse(fs.readFileSync("src/data/dua/slugs.lock.json", "utf8"));
  for (const [id, slug] of Object.entries(lk)) idBySlug.set(slug, id);
} catch { /* same */ }

/* The RENDERED page-intro line (.lede) is generated by build-dua-pages.mjs and never
   passes through page-copy.json, so scoping this check to the authored A1 alone let a
   fixed intro sentence sit on 333 pages unseen. It is templated text repeated across
   the library — exactly what this check exists to catch — so it is scanned here too,
   reported separately because it is generated rather than authored. */
function renderedLedes() {
  const out = [];
  let lock = {};
  try { lock = JSON.parse(fs.readFileSync("src/data/dua/slugs.lock.json", "utf8")); } catch { return out; }
  for (const slug of Object.values(lock)) {
    const f = "duas/" + slug + ".html";
    if (!fs.existsSync(f)) continue;
    const m = fs.readFileSync(f, "utf8").match(/<p class="lede">([\s\S]*?)<\/p>/);
    if (m) out.push([slug, m[1].replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim()]);
  }
  return out;
}

const wc = (s) => String(s || "").split(/\s+/).filter(Boolean).length;
const a1Of = (v) => [v.meaning, v.timing, v.reflection].filter(Boolean).join(" ");

const BANNED_OPENERS = [
  [/^This dua is/i, "This dua is"], [/^This powerful/i, "This powerful"],
  [/^One of the most/i, "One of the most"], [/^In Islam,/i, "In Islam,"],
  [/^Muslims believe/i, "Muslims believe"], [/^Are you looking for/i, "Are you looking for"],
  [/^In this article/i, "In this article"],
];
const BANNED_PHRASES = [
  [/it is important to note/i, "it is important to note"], [/plays a vital role/i, "plays a vital role"],
  [/serves as a reminder/i, "serves as a reminder"], [/rich tapestry/i, "rich tapestry"],
  [/delve into/i, "delve into"], [/in today's fast-paced world/i, "in today's fast-paced world"],
  [/\bmost powerful\b/i, "most powerful"], [/\bmiraculous\b/i, "miraculous"],
  [/\bguaranteed\b/i, "guaranteed"],
];
/* A time expression, a digit, or a capitalised proper noun mid-sentence. */
const TIME_RX = /\b(morning|evening|night|dawn|sunrise|sunset|before|after|during|while|upon|when|day|prayer|Tashahhud|Ruki|Sujood|ablution|rising|moment|leaving|entering|meeting|completion|completed|beginning|opening|prostration)\b/i;
const DIGIT_RX = /\d/;
/* A real proper-noun test rather than a whitelist: a capitalised token appearing
   somewhere other than the start of its sentence. Capitalised pronouns for Allah
   ("He", "Your") are excluded — they name no checkable particular. */
const CAP_STOP = new Set(["He","Him","His","You","Your","Yours","I","It","Its","The","A","An","And","But","Two","Three","Four","Five","Nothing","No","Both","Each","Every","Only","Unlike","Where","What","When"]);
function hasProperNoun(text) {
  for (const sentence of text.split(/(?<=[.!?])\s+/)) {
    const toks = sentence.trim().split(/\s+/);
    for (let i = 1; i < toks.length; i++) {
      const t = toks[i].replace(/^[("'‘’]+|[.,;:!?)"'‘’]+$/g, "");
      if (/^[A-Z][A-Za-z'’-]*$/.test(t) && !CAP_STOP.has(t)) return true;
    }
  }
  return false;
}

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim();

/* ---- per-entry checks ---- */
const problems = [];
for (const [slug, v] of entries) {
  const a1 = a1Of(v), w = wc(a1);
  const iss = [];
  if (w < 80 || w > 150) iss.push(`A1 word count ${w} outside 80-150`);
  for (const [rx, label] of BANNED_OPENERS)
    if (rx.test(String(v.meaning || "").trim())) iss.push(`banned opener: "${label}"`);
  for (const [rx, label] of BANNED_PHRASES)
    if (rx.test(a1)) iss.push(`banned phrase: "${label}"`);
  if (!(TIME_RX.test(a1) || DIGIT_RX.test(a1) || hasProperNoun(a1)))
    iss.push("no checkable specific (no digit, proper noun or time expression)");
  if (iss.length) problems.push({ slug, iss });
}

/* ---- §6.4 cross-page 12-gram overlap, A1 only, library-wide ---- */
const N = 12;
const gramPages = new Map();
for (const [slug, v] of entries) {
  const toks = norm(a1Of(v)).split(" ").filter(Boolean);
  const seen = new Set();
  for (let i = 0; i + N <= toks.length; i++) {
    const g = toks.slice(i, i + N).join(" ");
    if (seen.has(g)) continue;
    seen.add(g);
    if (!gramPages.has(g)) gramPages.set(g, []);
    gramPages.get(g).push(slug);
  }
}
const leaks = [...gramPages.entries()].filter(([, pages]) => pages.length >= 3)
  .sort((a, b) => b[1].length - a[1].length);

console.log("=".repeat(90));
console.log(`DUA A1 VALIDATION — ${entries.length} authored entries (library-wide)`);
console.log("=".repeat(90));
console.log("");
console.log(`§6.2/6.3/6.5 per-entry failures: ${problems.length}`);
for (const p of problems) console.log(`  ${p.slug}\n      ${p.iss.join("; ")}`);
console.log("");
console.log(`§6.4 twelve-gram sequences appearing on 3+ pages: ${leaks.length}`);
for (const [g, pages] of leaks.slice(0, 25)) {
  console.log(`  [${pages.length} pages] "${g}"`);
  for (const s of pages) console.log(`        ${s}`);
}
if (leaks.length > 25) console.log(`  … and ${leaks.length - 25} more`);
console.log("");
/* Also report 2-page repeats as a warning — not a spec failure, but the early
   signal that a formula is spreading. */
const pairs = [...gramPages.entries()].filter(([, p]) => p.length === 2);
console.log(`(advisory) 12-grams on exactly 2 pages: ${pairs.length}`);
console.log("");
/* ---- generated page-intro line, scanned library-wide ---- */
const ledes = renderedLedes();
const lg = new Map();
for (const [slug, text] of ledes) {
  const toks = norm(text).split(" ").filter(Boolean);
  const seen = new Set();
  for (let i = 0; i + N <= toks.length; i++) {
    const g = toks.slice(i, i + N).join(" ");
    if (seen.has(g)) continue; seen.add(g);
    if (!lg.has(g)) lg.set(g, []);
    lg.get(g).push(slug);
  }
}
const ledeLeaks = [...lg.entries()].filter(([, p]) => p.length >= 3).sort((a, b) => b[1].length - a[1].length);
console.log("=".repeat(90));
console.log(`GENERATED PAGE-INTRO (.lede) — ${ledes.length} rendered pages`);
console.log("=".repeat(90));
console.log(`  12-grams on 3+ pages: ${ledeLeaks.length}` +
  (ledeLeaks.length ? `   worst: ${ledeLeaks[0][1].length} pages` : ""));
for (const [g, p] of ledeLeaks.slice(0, 5)) console.log(`    [${p.length}] "${g}"`);
console.log("");

/* ---- Block B4 FAQ, scanned library-wide ----
   New generated text across every page that carries the block, so it gets the same
   12-gram treatment the lede needed. Answers are built from per-page facts, but the
   connective phrasing is shared and this is what catches it spreading. */
const faqTexts = [];
{
  let lockJ = {};
  try { lockJ = JSON.parse(fs.readFileSync("src/data/dua/slugs.lock.json", "utf8")); } catch {}
  for (const slug of Object.values(lockJ)) {
    const f = "duas/" + slug + ".html";
    if (!fs.existsSync(f)) continue;
    const m = fs.readFileSync(f, "utf8").match(/<h2>Common questions<\/h2>([\s\S]*?)<\/div>/);
    if (!m) continue;
    /* ANSWERS ONLY. The <h3> question text is excluded from the window, mirroring
       §6.4's existing carve-out for A2: "authentication notes legitimately repeat
       formulae". A reader's question ("What is the source for this?") is the same
       class — people really do ask the same handful of things on every page, and
       varying the question to dodge a checker would make the page worse.
       The carve-out stops at the question mark. Anything repeating inside an ANSWER
       is a connector, the same class as the dropped lede, and is fixed rather than
       exempted. */
    const answers = [...m[1].matchAll(/<p class="tr">([\s\S]*?)<\/p>/g)]
      .map((a) => a[1].replace(/<[^>]+>/g, " "));
    if (answers.length) faqTexts.push([slug, answers.join(" ").replace(/\s+/g, " ").trim()]);
  }
}
/* ---- B4 quoted-span carve-out (owner-approved 2026-08-02) ----------------------
   Same reasoning as the §6.4 A2 carve-out and the <h3> question carve-out above:
   text that is EXPECTED to repeat because it is the dua's own wording is not a
   templating leak. qMeaning quotes the record's `translation` verbatim, qTranslit
   quotes its `transliteration` verbatim, and qWhen / the `extra` sentences paste
   A1 (page-copy meaning / timing / reflection) verbatim. Four pages sharing the
   12-gram "there is no deity worthy of worship except allah alone he has" share it
   because four records carry that translation — varying it to satisfy a checker
   would mean misquoting the supplication.

   SCOPE IS DELIBERATELY NARROW. Only a span matching one of those five fields
   VERBATIM (after the same normalisation the window uses) is subtracted. The
   generated connective that introduces the quote ("In English it reads:") is NOT
   part of any field, so it stays inside the window — a connector spreading across
   pages is still caught, which is the whole point of the check.

   Each removed span leaves a BARRIER, not a join: dropping the tokens outright
   would let the words before a quote butt against the words after it and mint a
   12-gram that appears on no page. Windows are generated per surviving segment.

   The A1 text subtracted here is not going unchecked — §6.4 above scans the same
   prose library-wide on its own (currently 0 leaks). This removes a double count,
   it does not create a blind spot. */
const BARRIER = "\u0001";
function quotedSpansFor(slug) {
  const out = [];
  const push = (s) => { const n = norm(s); if (n.split(" ").filter(Boolean).length >= 3) out.push(n); };
  const rec = corpusById.get(idBySlug.get(slug));
  if (rec) { push(rec.translation); push(rec.transliteration); }
  const cp = pc[slug];
  if (cp) for (const f of [cp.meaning, cp.timing, cp.reflection]) {
    if (!f) continue;
    push(f);
    /* The FAQ pastes only the FIRST SENTENCE of meaning/reflection (see
       dua-faq-core _firstSentence), so the whole-field form never matches on its
       own. Each sentence of the field is still verbatim corpus-authored text. */
    for (const s of String(f).split(/(?<=[.!?])\s+/)) push(s);
  }
  /* longest first, so a sentence never eats part of the full field it belongs to */
  return [...new Set(out)].sort((a, b) => b.length - a.length);
}
function faqWindowText(slug, text) {
  let padded = " " + norm(text) + " ";
  for (const span of quotedSpansFor(slug)) {
    const needle = " " + span + " ";
    while (padded.includes(needle)) padded = padded.replace(needle, " " + BARRIER + " ");
  }
  return padded;
}

const fg = new Map();
let faqSpansRemoved = 0;
for (const [slug, text] of faqTexts) {
  const windowed = faqWindowText(slug, text);
  faqSpansRemoved += windowed.split(BARRIER).length - 1;
  const seen = new Set();
  for (const segment of windowed.split(BARRIER)) {
    const toks = segment.split(" ").filter(Boolean);
    for (let i = 0; i + N <= toks.length; i++) {
      const g = toks.slice(i, i + N).join(" ");
      if (seen.has(g)) continue; seen.add(g);
      if (!fg.has(g)) fg.set(g, []);
      fg.get(g).push(slug);
    }
  }
}
const faqLeaks = [...fg.entries()].filter(([, p]) => p.length >= 3).sort((a, b) => b[1].length - a[1].length);

/* B4 banned connectives. Each of these was padding added to hit the old 40-word
   floor, and each put an identical 12-gram across the 5-page pilot. The floor was
   removed 2026-08-02; these are banned by name so they cannot come back the next
   time an answer looks short. Same mechanism as the §4 banned-opener list. */
const FAQ_BANNED = [
  "it appears above as text",
  "not as a picture",
  "the full source line appears in the source",
  "the transliteration is given as text on this page",
  "so it can be copied and searched",
  "read by a screen reader",
  "read aloud by assistive software",
  "nothing here suggests a shorter version",
  "that count comes from the source text",
  "the number is taken from the source wording",
  "the citation is reproduced in the source",
  "where our record carries no grading",
  "nothing about its grading is stated here",
  "that length is a fact about the text on this page",
  "the count describes this text only",
];
const faqBanned = [];
for (const [slug, text] of faqTexts) {
  const n = norm(text);
  for (const p of FAQ_BANNED) if (n.includes(norm(p))) faqBanned.push(`${slug}: "${p}"`);
}
console.log("=".repeat(90));
console.log(`BLOCK B4 FAQ — ${faqTexts.length} pages carrying the block`);
console.log("=".repeat(90));
console.log(`  quoted spans subtracted from the window: ${faqSpansRemoved}` +
  `  (verbatim translation / transliteration / A1 only — owner-approved 2026-08-02)`);
console.log(`  12-grams on 3+ pages: ${faqLeaks.length}` + (faqLeaks.length ? `   worst: ${faqLeaks[0][1].length} pages` : ""));
for (const [g, p] of faqLeaks.slice(0, 5)) console.log(`    [${p.length}] "${g}"`);
console.log(`  banned connective phrases: ${faqBanned.length}`);
for (const b of faqBanned.slice(0, 6)) console.log(`    ${b}`);
console.log("");

console.log("-".repeat(90));
console.log(`RESULT  per-entry failures=${problems.length}  A1 leaks=${leaks.length}  lede leaks=${ledeLeaks.length}  FAQ leaks=${faqLeaks.length}  FAQ banned=${faqBanned.length}`);
process.exitCode = (problems.length || leaks.length) ? 1 : 0;
